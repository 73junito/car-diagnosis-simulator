create table if not exists public.diagnostic_data_domains (
    id bigint generated by default as identity primary key,
    slug text not null unique,
    name text not null,
    description text,
    processing_order integer not null default 100,
    created_at timestamptz not null default now()
);

create table if not exists public.external_resource_domain_links (
    resource_id bigint not null
        references public.external_data_resources(id)
        on delete cascade,
    domain_id bigint not null
        references public.diagnostic_data_domains(id)
        on delete cascade,
    usage_role text not null default 'reference'
        check (usage_role in (
            'primary',
            'enrichment',
            'reference',
            'research',
            'validation'
        )),
    primary key (resource_id, domain_id)
);

alter table public.diagnostic_data_domains enable row level security;
alter table public.external_resource_domain_links enable row level security;

