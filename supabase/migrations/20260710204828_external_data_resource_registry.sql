-- TorqueMind external data resource registry
-- Catalogs approved public, government, research, and training data sources.
-- This migration stores metadata only; it does not ingest third-party datasets.

create table if not exists public.external_data_resources (
    id bigint generated by default as identity primary key,
    slug text not null unique,
    name text not null,
    organization text,
    category text not null,
    description text,
    homepage_url text,
    api_url text,
    documentation_url text,
    additional_urls jsonb not null default '[]'::jsonb,
    diagnostic_domains text[] not null default '{}',
    access_type text not null default 'public'
        check (access_type in (
            'public',
            'public_api',
            'registration_required',
            'restricted',
            'research_portal'
        )),
    integration_priority integer not null default 3
        check (integration_priority between 1 and 5),
    integration_status text not null default 'planned'
        check (integration_status in (
            'planned',
            'evaluating',
            'approved',
            'integrated',
            'disabled'
        )),
    attribution_required boolean not null default true,
    commercial_use_review_required boolean not null default true,
    is_active boolean not null default true,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists external_data_resources_category_idx
    on public.external_data_resources(category);

create index if not exists external_data_resources_status_idx
    on public.external_data_resources(integration_status);

create index if not exists external_data_resources_priority_idx
    on public.external_data_resources(integration_priority);

create index if not exists external_data_resources_domains_gin_idx
    on public.external_data_resources using gin(diagnostic_domains);

create or replace function public.set_external_data_resource_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists external_data_resources_updated_at
    on public.external_data_resources;

create trigger external_data_resources_updated_at
before update on public.external_data_resources
for each row
execute function public.set_external_data_resource_updated_at();

alter table public.external_data_resources enable row level security;

drop policy if exists "External resources are publicly readable"
